// Regenerates apps/console/lucide_icons.go from the `lucide` npm package (ISC) for the names in
// apps/console/icon-names.txt (`old-name=current-file` keeps a renamed glyph). Usage: bun tools/gen-console-icons.ts <path-to-node_modules/lucide>
import { readFileSync, writeFileSync, existsSync } from "fs";
import { join } from "path";
const lucide = process.argv[2];
const root = join(import.meta.dir, "..");
const names = readFileSync(join(root, "apps/console/icon-names.txt"), "utf8").split(/\s+/).filter(Boolean);
const ver = JSON.parse(readFileSync(join(lucide, "package.json"), "utf8")).version;
const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const out: string[] = [];
for (const entry of names) {
  const [n, file = n] = entry.split("="); // "name=file": a former lucide name kept as an alias of the current file
  const f = join(lucide, "dist/esm/icons", `${file}.mjs`);
  if (!existsSync(f)) { console.warn("skip (not in lucide):", n); continue; }
  const node = (await import(f)).default as [string, Record<string, string>][];
  const inner = node.map(([t, a]) => `<${t}${Object.entries(a).map(([k, v]) => ` ${k}="${esc(v)}"`).join("")}></${t}>`).join("");
  out.push(`\t${JSON.stringify(n)}: ${JSON.stringify(inner)},`);
}
writeFileSync(join(root, "apps/console/lucide_icons.go"),
  `// Code generated by tools/gen-console-icons.ts from lucide ${ver} (ISC, https://lucide.dev). DO NOT EDIT.\n\npackage main\n\n` +
  `// consoleIcons holds the inner SVG markup of the Console glyphs (static, trusted data).\nvar consoleIcons = map[string]string{\n${out.join("\n")}\n}\n`);
console.log("icons:", out.length, "lucide", ver);
